import io, sys

def patch(path, pairs):
    with io.open(path, 'r', encoding='utf-8') as f:
        s = f.read()
    for old, new in pairs:
        if old not in s:
            print("WARN: not found in {}: {}".format(path, old))
        s = s.replace(old, new)
    with io.open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(s)
    print("OK", path)

